import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const countryPackRoot = path.join(repositoryRoot, "country-packs");
const outputPath = path.join(
  repositoryRoot,
  "src/data/generated/downloadableMedalCountryPackManifest.ts"
);
const descriptors = fs.readdirSync(countryPackRoot, { recursive: true })
  .filter((entry) => String(entry).endsWith("-descriptor.json"))
  .map((entry) => JSON.parse(fs.readFileSync(path.join(countryPackRoot, entry), "utf8")))
  .map((descriptor) => ({
    ...descriptor,
    albums: descriptor.albums.map(({
      cityName: _cityName,
      population: _population,
      rank: _rank,
      ...album
    }) => album)
  }))
  .sort((left, right) => left.countryCode.localeCompare(right.countryCode));

const source = `/* Generated by scripts/country-packs/build-downloadable-manifest.mjs. */
import type { MedalCountryCode, MedalLanguage } from "../../types/medal";

export type DownloadableMedalAlbumManifestEntry = {
  albumId: string;
  cityId: string;
  cityZoneId: string;
  countryCode: Exclude<MedalCountryCode, "fr">;
  localLanguage: MedalLanguage;
  medalCount: number;
  version: number;
};

export type DownloadableMedalCountryPackDescriptor = {
  albums: readonly DownloadableMedalAlbumManifestEntry[];
  compressedBytes: number;
  countryCode: Exclude<MedalCountryCode, "fr">;
  formatVersion: 1;
  languages: readonly MedalLanguage[];
  medalCount: number;
  publishedAt: string;
  sha256: string;
  uncompressedBytes: number;
  url: string;
  version: number;
};

export const DOWNLOADABLE_MEDAL_COUNTRY_PACKS:
  readonly DownloadableMedalCountryPackDescriptor[] = ${JSON.stringify(descriptors, null, 2)};
`;

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated downloadable manifest for ${descriptors.length} country packs.`);
